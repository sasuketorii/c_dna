"""Independent policy simulation, never human-confirmed data or promotion evidence.

First run --stage validation, then freeze the selected candidate before --stage test.
Test labels are not generated by the validation command. Re-runs are regression evidence.
"""

import os

for _name in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_name] = "1"

import argparse
import hashlib
import json
import resource
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression, SGDClassifier

from cdna_learner.worker import (
    KEYS,
    Record,
    calibration_test,
    eligible,
    evaluate,
    fit_calibration,
    fit_linear,
    pairs,
    select_margin,
)

METHODS = ("sgd30", "averaged_sgd30", "logistic10", "scaled_logistic10")
PROFILES = ("context_tradeoff", "narrow_signal", "nonlinear_target", "domain_conflict")
SIZES = (8, 32, 128, 512)
SEEDS = {"train": 41011, "validation": 52021, "calibration": 63031, "test": 74041}


def generate(profile, partition, count):
    """Labels use explicit policy equations, independently of worker.features()."""
    rng = np.random.default_rng(SEEDS[partition] + PROFILES.index(profile))
    rows = []
    day = list(SEEDS).index(partition) * 1000
    for i in range(count):
        stamp = (datetime(2020, 1, 1, tzinfo=UTC) + timedelta(days=day + i)).isoformat()
        pressure, assets, budget = rng.uniform(-1, 1, 3)
        domain = "product_delivery" if i % 2 == 0 else "risk_reputation"
        candidates, utilities = [], []
        for j in range(4):
            attrs = dict(zip(KEYS, map(float, rng.uniform(-1, 1, 6)), strict=True))
            if profile == "narrow_signal":
                attrs["speed"] *= 0.02
                utility = 0.9 * attrs["speed"] / 0.02 - 0.3 * attrs["effort"]
            elif profile == "nonlinear_target":
                # An interior optimum cannot be represented by the allowed linear features.
                utility = -((attrs["speed"] - pressure) ** 2) - 0.2 * attrs["cost"]
            elif profile == "domain_conflict":
                # Domain is deliberately not a feature: identical preferences cannot be inferred.
                utility = attrs["speed"] * (1 if domain == "product_delivery" else -1)
            else:
                utility = (
                    (0.25 + 0.9 * pressure) * attrs["speed"]
                    + (0.15 + 0.7 * assets) * attrs["reuse"]
                    - (0.2 + 0.65 * budget) * attrs["cost"]
                    - 0.3 * attrs["irreversibility"]
                )
            utilities.append(utility)
            candidates.append({"id": f"c{j}", "text": "Simulated option", "attributes": attrs})
        rows.append(
            Record.model_validate(
                {
                    "family_id": f"{profile}-{partition}-{i}",
                    "timestamp": stamp,
                    "domain": domain,
                    "context": {
                        "as_of": stamp,
                        "summary": "Independent simulated policy",
                        "unknown_fields": [],
                        "facts": [
                            {
                                "key": k,
                                "value": float(v),
                                "unit": "ratio",
                                "evidence_status": "explicit",
                            }
                            for k, v in (
                                ("deadline_pressure", pressure),
                                ("asset_importance", assets),
                                ("budget_pressure", budget),
                            )
                        ],
                    },
                    "candidates": candidates,
                    "chosen_ids": [f"c{int(np.argmax(utilities))}"],
                    "verification_state": "unconfirmed",
                    "model_exposure": False,
                    "answer_kind": "choose_one",
                    "case_kind": "hypothetical",
                }
            )
        )
    assert not any(eligible(r) for r in rows)
    return rows


def fit(records, method):
    start = time.perf_counter()
    if method == "scaled_logistic10":
        return fit_linear(records), (time.perf_counter() - start) * 1000
    x, y, sw = pairs(records)
    if method in ("sgd30", "averaged_sgd30"):
        clf = SGDClassifier(
            loss="log_loss",
            fit_intercept=False,
            random_state=17,
            learning_rate="constant",
            eta0=0.05,
            alpha=0.001,
            average=method == "averaged_sgd30",
        )
        for _ in range(30):
            clf.partial_fit(x, y, classes=[0, 1], sample_weight=sw)
        weights = clf.coef_[0]
    else:
        scale = np.ones(17)
        # Canonical numerical rows remove source/candidate ordering from the reduction order.
        order = np.lexsort((sw, y, *x.T))
        clf = LogisticRegression(C=10, fit_intercept=False, solver="lbfgs", tol=1e-8, max_iter=200)
        clf.fit(x[order] / scale, y[order], sample_weight=sw[order])
        weights = clf.coef_[0] / scale
    return weights, (time.perf_counter() - start) * 1000


def digest(rows):
    return hashlib.sha256("\n".join(r.model_dump_json() for r in rows).encode()).hexdigest()


def score(rows, weights, margin=0):
    return evaluate(rows, lambda x: x @ weights, margin, supported_masks=[0])


def validation():
    results = []
    for profile in PROFILES:
        train = generate(profile, "train", 512)
        valid = generate(profile, "validation", 200)
        assert not {r.family_id for r in train} & {r.family_id for r in valid}
        for size in SIZES:
            for method in METHODS:
                weights, elapsed = fit(train[:size], method)
                results.append(
                    {
                        "profile": profile,
                        "size": size,
                        "method": method,
                        "fit_ms": elapsed,
                        "validation": score(valid, weights),
                    }
                )
    means = {
        method: float(
            np.mean([r["validation"]["agreement"] for r in results if r["method"] == method])
        )
        for method in METHODS
    }
    selected = max(METHODS, key=lambda method: means[method])
    return {
        "selection": "equal mean across four predeclared profiles and four sizes",
        "selected": selected,
        "validation_means": means,
        "results": results,
        "test_generated": False,
    }


def final(selection):
    chosen = selection["selected"]
    results = []
    for profile in PROFILES:
        partitions = {
            k: generate(profile, k, n)
            for k, n in (("train", 512), ("validation", 200), ("calibration", 160), ("test", 240))
        }
        families = [{r.family_id for r in rows} for rows in partitions.values()]
        assert sum(map(len, families)) == len(set.union(*families))
        for size in SIZES:
            for method in dict.fromkeys(("sgd30", chosen)):
                weights, elapsed = fit(partitions["train"][:size], method)
                margin, status = select_margin(partitions["validation"], weights, [0])
                calibration = fit_calibration(partitions["calibration"], weights)
                results.append(
                    {
                        "profile": profile,
                        "size": size,
                        "method": method,
                        "fit_ms": elapsed,
                        "test": score(partitions["test"], weights),
                        "selective": score(partitions["test"], weights, margin),
                        "validation_status": status,
                        "margin": margin,
                        "calibration_test": calibration_test(
                            partitions["test"], weights, calibration
                        ),
                        "partition_hashes": {k: digest(v) for k, v in partitions.items()},
                    }
                )
    # Replacement correction: replay active rows from scratch, never count obsolete labels twice.
    repeat = []
    rows = generate("context_tradeoff", "train", 128)
    for method in dict.fromkeys(("sgd30", chosen)):
        base, elapsed = fit(rows, method)
        reverse, reverse_ms = fit(list(reversed(rows)), method)
        corrected = [r.model_copy(deep=True) for r in rows]
        for r in corrected[:16]:
            r.chosen_ids = [next(c.id for c in r.candidates if c.id not in r.chosen_ids)]
        times, weights = [], []
        for _ in range(5):
            w, ms = fit(corrected, method)
            times.append(ms)
            weights.append(w)
        restored, restore_ms = fit(rows, method)
        repeat.append(
            {
                "method": method,
                "original_fit_ms": elapsed,
                "reverse_fit_ms": reverse_ms,
                "order_max_weight_delta": float(np.max(np.abs(base - reverse))),
                "before_correction_16_cases": score(corrected[:16], base),
                "corrected_16_cases": score(corrected[:16], weights[0]),
                "retained_112_cases": score(corrected[16:], weights[0]),
                "correction_fit_median_ms": float(np.median(times)),
                "repeat_max_weight_delta": float(np.max(np.abs(weights[0] - weights[-1]))),
                "restore_fit_ms": restore_ms,
                "restore_max_weight_delta": float(np.max(np.abs(base - restored))),
            }
        )
    return {
        "selected": chosen,
        "test_used_for_selection": False,
        "results": results,
        "repeat_correction": repeat,
        "peak_rss_platform_units": resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--stage", choices=("validation", "test"), required=True)
    parser.add_argument("--selection", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.stage == "validation":
        result = validation()
    else:
        if args.selection is None:
            parser.error("test requires a frozen --selection validation receipt")
        selection = json.loads(args.selection.read_text())
        result = final(selection)
        result["selection_sha256"] = hashlib.sha256(args.selection.read_bytes()).hexdigest()
    result.update(
        {
            "benchmark_only": True,
            "human_labels": False,
            "model_exported": False,
            "seeds": SEEDS,
            "feature_version": "1.0",
            "benchmark_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
            "worker_sha256": hashlib.sha256(
                (Path(__file__).parents[1] / "src/cdna_learner/worker.py").read_bytes()
            ).hexdigest(),
        }
    )
    args.output.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    print(json.dumps({k: v for k, v in result.items() if k not in ("results",)}))


if __name__ == "__main__":
    main()
